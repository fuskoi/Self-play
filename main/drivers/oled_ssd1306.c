/*
 * 0.96" OLED · SSD1306 · I²C（与采购清单一致）
 * 手册要点（Solomon SSD1306）：
 *   - 从地址常见 0x3C（SA0=0）或 0x3D（SA0=1）
 *   - 控制字节：0x00=命令流，0x40=显存数据
 *   - 本驱动：128×64，水平寻址，帧缓冲整屏刷新
 * 接线：SDA=GPIO8，SCL=GPIO9，与双 ToF 共总线
 */

