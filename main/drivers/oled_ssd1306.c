#define OLED_H            64
#define OLED_PAGES        (OLED_H / 8)
#define OLED_ADDR_PRIMARY 0x3C
#define OLED_ADDR_ALT     0x3D
#define OLED_I2C_TIMEOUT  pdMS_TO_TICKS(100)

